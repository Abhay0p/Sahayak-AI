const dictionary: Record<LanguageCode, Translations> = Object.keys(LANGUAGES).reduce((acc, key) => {
  const langKey = key as LanguageCode;
  acc[langKey] = baseDictionary[langKey] || {};
  return acc;
}, {} as Record<LanguageCode, Translations>);

export const getTranslation = (lang: LanguageCode, key: string, fallbackText: string = ''): string => {
  const translations = dictionary[lang] || {};
  // Return translated value if available
  if (translations[key]) return translations[key];
  // Fall back to English dictionary key if present
  if (dictionary['en'] && dictionary['en'][key]) return dictionary['en'][key];
  return fallbackText || key;
};

